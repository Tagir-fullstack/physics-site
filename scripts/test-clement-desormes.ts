import assert from 'node:assert/strict'
import { AIR_GAMMA, CLEMENT_READING_ERROR_BOUND_MM, CLEMENT_TIMES, clementAction, clementExpected, clementFinalHead, clementFit, clementGamma, clementReading, clementVariant, freshClement, stepClement } from '../src/lib/clementDesormes.js'
const fingerprints = new Set<string>()
for (let number = 1; number <= 1000; number++) {
  const v = clementVariant(number)
  assert.deepEqual(v, clementVariant(number))
  fingerprints.add(JSON.stringify([v.targetHead, v.ambientK, v.pressurePa, v.heatLeak]))
  assert.ok(v.targetHead >= 180 && v.targetHead <= 260)
  const expected = clementExpected(v)
  const fit = clementFit(expected.trials.map(r => ({ time: r.time, head: r.head })))!
  assert.ok(Math.abs(fit.slope + v.heatLeak) < 1e-12)
  assert.ok(Math.abs(clementGamma(v.targetHead, fit.head)! - AIR_GAMMA) < 1e-12)
  assert.ok(expected.trials.every((r, i) => r.head > 0 && (i === 0 || r.head < expected.trials[i - 1].head)))
  for (const time of CLEMENT_TIMES) {
    let s = freshClement(v)
    assert.deepEqual(clementAction(v, s, 'outlet'), s)
    assert.deepEqual(clementAction(v, s, 'pump-on'), s)
    s = clementAction(v, s, 'inlet'); s = clementAction(v, s, 'pump-on')
    s = stepClement(v, s, 12)
    assert.equal(s.equilibriumHead, v.targetHead)
    assert.ok(s.temperatureK > v.ambientK)
    assert.ok(s.head > v.targetHead)
    s = clementAction(v, s, 'pump-off'); s = clementAction(v, s, 'inlet')
    assert.equal(s.phase, 'settling')
    assert.deepEqual(clementAction(v, s, 'outlet'), s)
    s = stepClement(v, s, 80)
    assert.equal(s.phase, 'ready'); assert.equal(s.head, v.targetHead)
    s = clementAction(v, s, 'outlet')
    assert.equal(s.phase, 'venting')
    const early = stepClement(v, s, .5)
    assert.ok(early.temperatureK < v.ambientK)
    assert.equal(clementAction(v, early, 'outlet').phase, 'venting', 'Closing before pressure equalization is blocked')
    s = stepClement(v, s, time)
    assert.equal(s.head, 0); assert.equal(s.ventTime, time)
    assert.ok(s.temperatureK < v.ambientK)
    s = clementAction(v, s, 'outlet')
    assert.equal(s.phase, 'warming')
    const intermediate = stepClement(v, s, 20)
    assert.ok(intermediate.head > 0 && intermediate.head < s.finalHead)
    assert.ok(intermediate.temperatureK > s.temperatureK && intermediate.temperatureK < v.ambientK)
    s = stepClement(v, s, 80)
    assert.equal(s.phase, 'complete'); assert.equal(s.temperatureK, v.ambientK)
    assert.ok(Math.abs(s.head - clementFinalHead(v, v.targetHead, time)) < 1e-12)
    const reading = clementReading(v, s)
    assert.deepEqual(reading, clementReading(v, s))
    assert.equal(reading.difference, reading.right - reading.left)
    assert.ok(Math.abs(reading.difference - s.head) <= CLEMENT_READING_ERROR_BOUND_MM)
    assert.deepEqual(clementAction(v, s, 'reset'), freshClement(v, 1))
  }
}
assert.ok(fingerprints.size > 990)
assert.equal(clementFit([{ time: 5, head: 0 }, { time: 10, head: 3 }]), null)
assert.equal(clementFit([{ time: 5, head: 3 }, { time: 5, head: 4 }]), null)
assert.equal(clementGamma(200, 200), null)
assert.equal(clementGamma(200, -5), null)
assert.equal(clementGamma(NaN, 10), null)
for (const bad of [0, -1, 1.5, NaN, Infinity]) assert.throws(() => clementVariant(bad))
const v = clementVariant(24)
let longFrame = clementAction(v, clementAction(v, freshClement(v), 'inlet'), 'pump-on')
for (let i = 0; i < 120; i++) longFrame = stepClement(v, longFrame, .1)
longFrame = clementAction(v, clementAction(v, longFrame, 'pump-off'), 'inlet')
longFrame = stepClement(v, longFrame, 800)
assert.equal(longFrame.phase, 'ready', 'Large frame intervals preserve physical elapsed time')
assert.equal(stepClement(v, longFrame, NaN), longFrame)
console.log('PASS: 1000 deterministic variants, 5000 full trials, valve interlocks, heating/cooling, 80 s equilibrium, measured levels, logarithmic extrapolation, gamma and input validation')

// Instrument errors affect measured initial/final levels, not the physical state or the permanent assignment.
const samples = new Set<string>()
for (let run = 0; run < 100; run++) {
  const ready = { ...freshClement(v, run), phase: 'ready' as const, head: v.targetHead }
  const final = { ...ready, phase: 'complete' as const, ventTime: 5, head: clementFinalHead(v, v.targetHead, 5) }
  const before = JSON.stringify(final)
  const measured = clementReading(v, final)
  assert.ok(Math.abs(measured.difference - final.head) <= CLEMENT_READING_ERROR_BOUND_MM)
  assert.ok(Math.abs(clementReading(v, ready).difference - ready.head) <= CLEMENT_READING_ERROR_BOUND_MM)
  assert.deepEqual(measured, clementReading(v, final), 'Reading must not flicker between frames')
  assert.equal(JSON.stringify(final), before, 'Reading error must not change the physical state')
  assert.equal(clementReading(v, freshClement(v, run)).difference, 0, 'Both limbs start level')
  samples.add(JSON.stringify(measured))
}
assert.ok(samples.size >= 3, 'Repeated trials must have different observed readings')
console.log('PASS: stable instrument errors, repeat variation, initial/final error bounds and unchanged physics')
